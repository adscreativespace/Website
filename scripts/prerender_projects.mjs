// Gives every project its own real page for Google:
//   projects/<slug>.html      (English, from project.html)
//   bn/projects/<slug>.html   (Bengali, from bn/project.html + bn/projects/<slug>.json)
// Each page is project.html opened in a headless browser and saved after it has drawn the project, with its own
// title, description, canonical address, social preview, structured data and language links in the HTML itself.
// The page's own script still runs for visitors (lightbox, latest data), so nothing changes for people.
// Run by .github/workflows/project-index.yml whenever a project is published from the CMS, or by hand:
//   npm i --prefix /tmp/pr playwright js-yaml && npx --prefix /tmp/pr playwright install chromium
//   NODE_PATH=/tmp/pr/node_modules node scripts/prerender_projects.mjs
import { createRequire } from "module";
import http from "http";
import fs from "fs";
import path from "path";
const require = createRequire(import.meta.url);
const { chromium } = require("playwright");

const ROOT = process.cwd(), SITE = "https://adscreativespace.com/";
const MARK = "<!-- Generated by scripts/prerender_projects.mjs from {tpl}. Do not edit: change the project in the CMS. -->";
const TYPES = { ".html": "text/html; charset=utf-8", ".js": "text/javascript", ".css": "text/css", ".json": "application/json", ".md": "text/plain; charset=utf-8",
  ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp", ".svg": "image/svg+xml", ".ico": "image/x-icon" };
let YAML = null;
try { const d = path.dirname(require.resolve("js-yaml/package.json")); YAML = fs.readFileSync(path.join(d, "dist/js-yaml.min.js")); } catch (e) { console.warn("js-yaml not installed locally; using the CDN copy"); }

const esc = s => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const slugs = fs.readdirSync(path.join(ROOT, "projects")).filter(n => n.endsWith(".md")).map(n => n.slice(0, -3)).sort();

const server = http.createServer((req, res) => {
  const u = decodeURIComponent(new URL(req.url, "http://x").pathname), f = path.join(ROOT, u.endsWith("/") ? u + "index.html" : u);
  if (!f.startsWith(ROOT) || !fs.existsSync(f) || fs.statSync(f).isDirectory()) { res.writeHead(404); return res.end(); }
  res.writeHead(200, { "Content-Type": TYPES[path.extname(f).toLowerCase()] || "application/octet-stream" }); fs.createReadStream(f).pipe(res);
}).listen(0, "127.0.0.1");
await new Promise(r => server.once("listening", r));
const BASE = `http://127.0.0.1:${server.address().port}/`;

const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
await ctx.addInitScript(() => { window.__PRERENDER__ = true; });
await ctx.route(/^https?:\/\/(?!127\.0\.0\.1)/, r => {
  if (YAML && /js-yaml/.test(r.request().url())) return r.fulfill({ status: 200, contentType: "text/javascript", body: YAML });
  if (/js-yaml/.test(r.request().url())) return r.continue();
  return r.abort();   // fonts, icons, analytics: not needed to read the text
});
const page = await ctx.newPage();
const problems = [];

for (const lang of ["en", "bn"]) {
  const tplPath = lang === "bn" ? "bn/project.html" : "project.html", outDir = lang === "bn" ? "bn/projects" : "projects";
  const tpl = fs.readFileSync(path.join(ROOT, tplPath), "utf8");
  for (const slug of slugs) {
    await page.goto(BASE + tplPath + "?slug=" + encodeURIComponent(slug), { waitUntil: "domcontentloaded" });
    try { await page.waitForSelector("#pd-root .pd-hero h1", { timeout: 20000 }); } catch (e) { problems.push(`${lang}/${slug}: did not draw`); continue; }
    const d = await page.evaluate(() => {
      const a = (id, at) => document.getElementById(id)?.getAttribute(at) || "";
      return { title: document.title, desc: a("meta-desc", "content"), canon: a("meta-canonical", "href"), ogt: a("og-title", "content"), ogd: a("og-desc", "content"),
        ogu: a("og-url", "content"), ogi: a("og-image", "content"), ld: document.getElementById("ld-project")?.textContent || "", root: document.getElementById("pd-root").innerHTML.trim() };
    });
    const en = SITE + "projects/" + slug + ".html", bn = SITE + "bn/projects/" + slug + ".html", self = lang === "bn" ? bn : en;
    if (d.canon !== self) problems.push(`${lang}/${slug}: canonical ${d.canon}`);
    let h = tpl;
    const sub = (re, val, what) => { if (!re.test(h)) problems.push(`${lang}/${slug}: no ${what}`); h = h.replace(re, val); };
    sub(/<title>[\s\S]*?<\/title>/, `<title>${esc(d.title)}</title>`, "title");
    sub(/(<meta name="description" id="meta-desc" content=")[^"]*(")/, `$1${esc(d.desc)}$2`, "description");
    sub(/(<link rel="canonical" id="meta-canonical" href=")[^"]*(")/, `$1${self}$2`, "canonical");
    sub(/(id="og-title" content=")[^"]*(")/, `$1${esc(d.ogt)}$2`, "og:title");
    sub(/(id="og-desc" content=")[^"]*(")/, `$1${esc(d.ogd)}$2`, "og:description");
    sub(/(id="og-url" content=")[^"]*(")/, `$1${self}$2`, "og:url");
    if (d.ogi) sub(/(id="og-image" content=")[^"]*(")/, `$1${esc(d.ogi)}$2`, "og:image");
    if (!/<base href="\/">/.test(h)) h = h.replace(/(<meta charset="UTF-8">)/i, '$1\n  <base href="/">');
    h = h.replace("</head>", `  <link rel="alternate" hreflang="en" href="${en}">\n  <link rel="alternate" hreflang="bn" href="${bn}">\n  <link rel="alternate" hreflang="x-default" href="${en}">\n` +
      (d.ld ? `  <script type="application/ld+json" id="ld-project">${d.ld.replace(/</g, "\\u003c")}</script>\n` : "") +
      `  <script>window.__SLUG__ = ${JSON.stringify(slug)};</script>\n</head>`);
    sub(/<div id="pd-root">\s*<div style="padding:140px;[\s\S]*?<\/div>\s*<\/div>/, `<div id="pd-root">\n${d.root}\n  </div>`, "project area");
    sub(lang === "bn" ? /href="project\.html" class="lang-switch"/ : /href="bn\/project\.html" class="lang-switch"/,
      `href="${lang === "bn" ? "projects/" : "bn/projects/"}${slug}.html" class="lang-switch"`, "language link");
    h = h.replace(/(<html[^>]*>)/, `$1\n${MARK.replace("{tpl}", tplPath)}`);
    fs.mkdirSync(path.join(ROOT, outDir), { recursive: true });
    fs.writeFileSync(path.join(ROOT, outDir, slug + ".html"), h);
  }
  // remove pages of projects that were deleted
  for (const n of fs.readdirSync(path.join(ROOT, outDir))) {
    if (n.endsWith(".html") && !slugs.includes(n.slice(0, -5)) && fs.readFileSync(path.join(ROOT, outDir, n), "utf8").includes("Generated by scripts/prerender_projects.mjs")) fs.unlinkSync(path.join(ROOT, outDir, n));
  }
}
await browser.close(); server.close();
console.log(`${slugs.length} projects × 2 languages written.`);
if (problems.length) { console.error("Problems:\n  " + problems.join("\n  ")); process.exit(1); }
